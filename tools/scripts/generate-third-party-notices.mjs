#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from the packages that esbuild actually
// bundles into apps/agentd/dist/pi-agentd.cjs.
//
// Usage: node tools/scripts/generate-third-party-notices.mjs [--check]
//   --check  exit 1 if the committed file is out of date (for CI).
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const agentdDir = join(repoRoot, 'apps', 'agentd');
// esbuild is a devDependency of apps/agentd, so resolve it from there.
const { build } = createRequire(join(agentdDir, 'package.json'))('esbuild');
const outFile = join(repoRoot, 'THIRD_PARTY_NOTICES.md');

const result = await build({
  absWorkingDir: agentdDir,
  entryPoints: ['src/main.ts'],
  bundle: true,
  platform: 'node',
  target: 'node22',
  write: false,
  outfile: 'pi-agentd.cjs',
  metafile: true,
  logLevel: 'error',
});

// Map package name -> package directory, taken from the bundled input paths.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const marker = 'node_modules/';
  const index = input.lastIndexOf(marker);
  if (index < 0) continue;
  const parts = input.slice(index + marker.length).split('/');
  const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
  if (packages.has(name)) continue;
  const packageDir = resolve(agentdDir, input.slice(0, index + marker.length) + name);
  packages.set(name, packageDir);
}

function licenseText(packageDir) {
  const file = readdirSync(packageDir).find((entry) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(entry));
  return file ? readFileSync(join(packageDir, file), 'utf8').replace(/\r\n/g, '\n').trim() : null;
}

const sections = [...packages.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, dir]) => {
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const text = licenseText(dir);
    if (!text) throw new Error(`No license file found for ${name} in ${dir}`);
    const homepage = manifest.homepage ? ` (${manifest.homepage})` : '';
    return `### ${name} ${manifest.version}\n\nLicense: ${manifest.license}${homepage}\n\n\`\`\`text\n${text}\n\`\`\``;
  });

const content = `# Third-party notices

PiFrame is released under the MIT License (see \`LICENSE\`). PiFrame installers
also ship third-party software, listed below with its license.

## Node.js runtime

The installers include the Node.js runtime that runs \`pi-agentd\`. Its license
is shipped next to it as \`NODE-LICENSE.txt\` (MIT, with the notices of the
components that Node.js bundles).

## Flutter and Dart packages

The desktop app is built with Flutter. The licenses of the Flutter engine and
of every Dart package the app uses are collected automatically by Flutter at
build time and shipped inside the app (\`flutter_assets/NOTICES\`).

## npm packages bundled into pi-agentd

<!-- Generated by tools/scripts/generate-third-party-notices.mjs. Do not edit by hand. -->

${sections.join('\n\n')}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== content) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run: node tools/scripts/generate-third-party-notices.mjs');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(outFile, content);
  console.log(`Wrote ${outFile} (${packages.size} packages).`);
}
